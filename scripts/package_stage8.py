"""Prepare an explicit, reviewable Git source export without initializing/pushing Git."""
from pathlib import Path
import hashlib,json,shutil,tarfile

ROOT=Path(__file__).resolve().parents[1]
TOP=['.gitignore','.vercelignore','.python-version','AGENTS.md','README.md','app.py','vercel_app.py','vercel.json','pyproject.toml','requirements.txt','requirements.in','requirements-dev.lock.txt']
BLOCKED={'.env','.venv','.git','.vercel','node_modules','__pycache__','history','received','transcripts','tmp'}

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def source_files():
    files={ROOT/p for p in TOP}
    for folder,patterns in [('l7_analysis',['*.py']),('l7_service',['*.py']),('scripts',['*.py','*.mjs']),('tests',['*.py']),('docs',['*.md','*.txt','*.json']),('reports/source',['*.py','*.md','report-data.json']),('artifacts/analysis',['*']),('artifacts/feasibility',['*'])]:
        for pattern in patterns:
            for p in (ROOT/folder).rglob(pattern):
                if not p.is_file():continue
                rel=p.relative_to(ROOT)
                if any(x in BLOCKED for x in rel.parts):continue
                if p==ROOT/'docs/notebooklm/review.json':continue
                files.add(p)
    files.update(p for p in (ROOT/'web').rglob('*') if p.is_file())
    # Primary-source definitions and attribution, not LMS content or duplicate raw CSV.
    for pattern in ['artifacts/reference/datasets-manifest.json','artifacts/reference/datasets/*metadata.json','artifacts/reference/datasets/sgemm-readme.txt','artifacts/reference/datasets/student-dictionary.txt']:
        files.update(ROOT.glob(pattern))
    for p in (ROOT/'reports/output/pdf').glob('*.pdf'):files.add(p)
    # Retain prior verified evidence; ephemeral request fixtures and screenshots are separate.
    for prefix in ['stage2','stage3','stage4','stage5','stage6','stage7','notebooklm','predictor-layout','lecture6-removal']:
        files.update(p for p in (ROOT/'artifacts/validation').glob(prefix+'*.json') if p.is_file() and p.stat().st_size<2_000_000)
    files.add(ROOT/'artifacts/validation/screenshots/stage6/final-six-methods.jpg')
    for p in files:
        rel=p.relative_to(ROOT)
        if p.is_symlink() or not p.is_file() or any(x in BLOCKED for x in rel.parts) or p.name.startswith('.env') or p.suffix.lower() in {'.key','.pem'}:
            raise ValueError('Unexpected file in publication allowlist: '+str(rel))
        if 'Lecture6_conversation_snapshot' in p.name:raise ValueError('Retired conversation cannot be published')
    return sorted(files)

def main():
    paths=source_files()
    records=[{'path':p.relative_to(ROOT).as_posix(),'source_absolute_path':str(p),'bytes':p.stat().st_size,'sha256':sha(p)} for p in paths]
    package_id=hashlib.sha256(json.dumps([{k:v for k,v in x.items() if k!='source_absolute_path'} for x in records],sort_keys=True,separators=(',',':')).encode()).hexdigest()
    destination=ROOT/'artifacts/deployment'/package_id[:16]
    source=destination/'source';source.mkdir(parents=True,exist_ok=True)
    for p,entry in zip(paths,records):
        dest=source/entry['path'];dest.parent.mkdir(parents=True,exist_ok=True)
        if not dest.exists() or sha(dest)!=entry['sha256']:shutil.copyfile(p,dest)
    assert {p.relative_to(source).as_posix() for p in source.rglob('*') if p.is_file()}=={x['path'] for x in records}
    # Vercel CLI source subset: public/ is generated by buildCommand, never uploaded here.
    upload=[x for x in records if x['path'] in {'vercel_app.py','app.py','pyproject.toml','vercel.json','.python-version','requirements.txt','.vercelignore','scripts/build_vercel_static.py'} or x['path'].startswith(('web/','l7_analysis/','l7_service/'))]
    manifest={'status':'local_source_export_not_published','package_id':package_id,'proposed_name':'l7-crispdm-mr','github_owner':None,'github_remote':None,'vercel_team':None,'vercel_project_id':None,'vercel_region':None,'source_directory':str(source),'github_files':records,'github_file_count':len(records),'github_source_bytes':sum(x['bytes'] for x in records),'vercel_upload_files':upload,'vercel_upload_bytes':sum(x['bytes'] for x in upload),'public_downloads':[x for x in records if x['path'].startswith('web/downloads/')],'excluded':['secrets/provider state','local .venv and caches','raw/processed datasets','LMS assignment snapshots','history and validation request fixtures','NotebookLM original pasted text and local research PDF','conversation source JSON','PDF render temporary files','retired Lecture6 PDF'],'limitations':['No Git repository or cloud resource created.','Requires actual GitHub/Vercel identity, plan, project and region verification before publication.','HW2 conversation PDF is in public downloads; user review required before publication.','Linux wheel size is measured separately; this source package is not a Vercel build output.']}
    (destination/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    archive=destination/'l7-crispdm-mr-source.tar.gz'
    if not archive.exists():
        with tarfile.open(archive,'w:gz') as tar:
            for entry in records:tar.add(source/entry['path'],arcname='l7-crispdm-mr/'+entry['path'],recursive=False)
    receipt={'package_id':package_id,'manifest':str((destination/'manifest.json').relative_to(ROOT)),'source_directory':str(source.relative_to(ROOT)),'archive':str(archive.relative_to(ROOT)),'archive_bytes':archive.stat().st_size,'archive_sha256':sha(archive),'github_file_count':len(records),'github_source_bytes':manifest['github_source_bytes'],'vercel_upload_bytes':manifest['vercel_upload_bytes']}
    (ROOT/'artifacts/validation/stage8-package.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(receipt,ensure_ascii=False))

if __name__=='__main__':main()
